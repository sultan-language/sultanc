#!/usr/bin/env python3
"""Generate the per-architecture Linux syscall number tables of std.

Each table maps the std operations (tools/generate/registry/linux_syscalls.def)
to the __NR_ numbers of one Linux architecture, read from that architecture's
kernel UAPI headers through `clang -E -dM`, so the kernel's own conditionals
(__ARCH_WANT_*, __NR_Linux bases) decide every value.

Headers: Debian/Ubuntu `linux-libc-dev-<arch>-cross` packages (or a kernel
`make headers_install`). Pass each include directory with --include:

  tools/generate/generate_linux_syscalls.py \
      --include x86_64=/usr/include/x86_64-linux-gnu:/usr/include \
      --include aarch64=/usr/aarch64-linux-gnu/include ...

Architectures without --include are left unchanged. A registry name written
`ilp32:<name>` is tried first on the 32-bit ABIs only (their time64 and
mmap2 entry points) and skipped elsewhere.
"""
import argparse, re, subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT_DIR = ROOT / "library/std/os/platform/unix/linux/syscalls"
REGISTRY = ROOT / "tools/generate/registry/linux_syscalls.def"

# arch key: (clang triple, output file, function name, source note)
ARCHES = {
    "x86_64": ("x86_64-linux-gnu", "numbers_x86_64.sn", "رقم_نداء_نواة_لينكس_اكس86_64", "arch/x86/entry/syscalls/syscall_64.tbl"),
    "aarch64": ("aarch64-linux-gnu", "numbers_asm_generic_64.sn", "رقم_نداء_نواة_لينكس_اسم_غالب_64", "include/uapi/asm-generic/unistd.h (arm64)"),
    "riscv64": ("riscv64-linux-gnu", "numbers_riscv64.sn", "رقم_نداء_نواة_لينكس_رايسك_في_64", "include/uapi/asm-generic/unistd.h (riscv64)"),
    "loongarch64": ("loongarch64-linux-gnu", "numbers_loongarch64.sn", "رقم_نداء_نواة_لينكس_لونغ_آرتش_64", "include/uapi/asm-generic/unistd.h (loongarch64)"),
    "powerpc64": ("powerpc64le-linux-gnu", "numbers_powerpc64.sn", "رقم_نداء_نواة_لينكس_باور_بي_سي_64", "arch/powerpc/kernel/syscalls/syscall.tbl (64-bit)"),
    "s390x": ("s390x-linux-gnu", "numbers_s390x.sn", "رقم_نداء_نواة_لينكس_إس390_إكس", "arch/s390/kernel/syscalls/syscall.tbl (64-bit)"),
    "mips64": ("mips64el-linux-gnuabi64", "numbers_mips64.sn", "رقم_نداء_نواة_لينكس_ميبس_64", "arch/mips/kernel/syscalls/syscall_n64.tbl"),
    "sparcv9": ("sparc64-linux-gnu", "numbers_sparc64.sn", "رقم_نداء_نواة_لينكس_سبارك_64", "arch/sparc/kernel/syscalls/syscall.tbl (64-bit)"),
    "x86": ("i386-linux-gnu", "numbers_i386.sn", "رقم_نداء_نواة_لينكس_اكس86_32", "arch/x86/entry/syscalls/syscall_32.tbl"),
    "arm": ("arm-linux-gnueabihf", "numbers_arm_eabi.sn", "رقم_نداء_نواة_لينكس_ذراع_32", "arch/arm/tools/syscall.tbl (EABI)"),
}

# 32-bit ABIs (time64 and large-file entry points).
ILP32 = {"x86", "arm"}


def macros(triple, includes):
    cmd = ["clang", f"--target={triple}", "-nostdinc"]
    for inc in includes:
        cmd += ["-I", inc]
    cmd += ["-E", "-dM", "-include", "asm/unistd.h", "-"]
    text = subprocess.run(cmd, input="", capture_output=True, text=True, check=True).stdout
    table = {}
    for line in text.splitlines():
        m = re.match(r"#define (\w+) (.+)", line)
        if m:
            table[m.group(1)] = m.group(2).strip()
    return table


def evaluate(name, table, depth=0):
    if depth > 20 or name not in table:
        return None
    expr = re.sub(r"\b(__NR\w*|__NR_Linux\w*)\b",
                  lambda m: str(evaluate(m.group(1), table, depth + 1)), table[name])
    expr = re.sub(r"(\d+)U?L*\b", r"\1", expr)
    try:
        return int(eval(expr, {"__builtins__": {}}))
    except Exception:
        return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--include", action="append", default=[], help="arch=dir[:dir]")
    args = ap.parse_args()
    rows = []
    for line in REGISTRY.read_text(encoding="utf-8").splitlines():
        if line.strip() and not line.startswith("#"):
            parts = line.split()
            rows.append((parts[0], parts[1:]))
    for spec in args.include:
        arch, dirs = spec.split("=", 1)
        triple, out, func, note = ARCHES[arch]
        table = macros(triple, dirs.split(":"))
        lines = [
            "// GENERATED by tools/generate/generate_linux_syscalls.py. Do not edit.",
            "استورد os.platform.unix.linux.syscalls.operations;",
            "",
            f"// Linux kernel UAPI: {note}",
            "// These are numeric ABI descriptions, not calls to libc syscall().",
            "// A target-selected machine syscall entry must execute the operation.",
            f"عام عرف {func}(العملية: عملية_نداء_نواة_لينكس): طبيعي {{",
            "    طابق العملية مع",
        ]
        for i, (op, names) in enumerate(rows):
            value, used = None, None
            for nr in names:
                if nr.startswith("ilp32:"):
                    if arch not in ILP32:
                        continue
                    nr = nr[len("ilp32:"):]
                if nr == "-":
                    value, used = 0xFFFFFFFF, "none (ENOSYS)"
                    break
                value = evaluate("__NR_" + nr, table)
                if value is not None:
                    used = nr
                    break
            if value is None:
                raise SystemExit(f"{arch}: no __NR_ for {op} ({names})")
            end = ";" if i + 1 == len(rows) else ""
            lines.append(f"    | عملية_نداء_نواة_لينكس.{op} -> {{ أرجع {value}; }}{end} // " + (used if used.startswith("none") else "__NR_" + used))
        lines += ["}", ""]
        (OUT_DIR / out).write_text("\n".join(lines), encoding="utf-8")
        print(arch, "->", out)


if __name__ == "__main__":
    main()
