#!/usr/bin/env python3
"""Writes library/std/math/wrapping.sn: wrapping, checked and saturating
integer arithmetic for every integer type (Rust's wrapping_*/checked_*/
saturating_*). The wrapping operations are the
compiler's non-trapping intrinsics; checked and saturating ones detect the
overflow from the wrapped result, without masks or wider arithmetic.

Regenerate with: python3 tools/generate/generate_wrapping_arithmetic.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "library/std/math/wrapping.sn"

# (Arabic type, English suffix, bits, signed)
TYPES = [
    ("ص8", "i8", 8, True), ("ص16", "i16", 16, True), ("ص32", "i32", 32, True), ("ص64", "i64", 64, True),
    ("عدد", "int", 64, True),
    ("ط8", "u8", 8, False), ("ط16", "u16", 16, False), ("ط32", "u32", 32, False), ("ط64", "u64", 64, False),
    ("طبيعي", "uint", 64, False),
]
# Names std.math.integer already defines (same contract); not repeated here.
EXISTING = {"جمع_طبيعي_متحقق", "طرح_طبيعي_متحقق", "ضرب_طبيعي_متحقق", "جمع_طبيعي_مشبع",
            "طرح_طبيعي_مشبع", "ضرب_طبيعي_مشبع", "جمع_عدد_متحقق", "طرح_عدد_متحقق", "ضرب_عدد_متحقق"}


def bounds(bits, signed):
    if signed:
        lo = -(1 << (bits - 1))
        hi = (1 << (bits - 1)) - 1
        lo_lit = f"({lo + 1} - 1)" if bits == 64 else f"({lo})"
        return lo_lit, str(hi)
    return "0", str((1 << bits) - 1)


def narrow_mul(T, bits, signed, lo, hi, on_ok, on_over):
    W = "ص64" if signed else "ط64"
    return (f"    دع الناتج: {W} = (أ مثل {W}) * (ب مثل {W});\n"
            f"    إذا (الناتج < ({lo} مثل {W}) || الناتج > ({hi} مثل {W})) {{ {on_over} }};\n"
            f"    {on_ok.replace('@', f'الناتج مثل {T}')}\n")


def main():
    out = []
    w = out.append
    w("// Wrapping, checked and saturating integer arithmetic for every integer type.")
    w("// Generated by tools/generate/generate_wrapping_arithmetic.py; do not edit.")
    w("//")
    w("// - `جمع_T_ملتف` / `wrapping_add_T` (also طرح, ضرب): the result modulo 2^N, never")
    w("//   a trap (Rust's wrapping_add, Go's unsigned arithmetic).")
    w("// - `إزاحة_يسرى_T_ملتفة` / `wrapping_shl_T` (and يمنى): the amount is taken modulo")
    w("//   the width, as Rust's wrapping_shl; a right shift of a signed type is arithmetic.")
    w("// - `جمع_T_متحقق` / `checked_add_T`: none on overflow (Rust's checked_add).")
    w("// - `جمع_T_مشبع` / `saturating_add_T`: clamped to the type's bounds.")
    w("// The uint and int checked operations and the uint saturating ones are in")
    w("// std.math.integer, which defined them first.")
    w("")
    for p in ["جمع_ملتف", "طرح_ملتف", "ضرب_ملتف", "إزاحة_يسرى_ملتفة", "إزاحة_يمنى_ملتفة"]:
        w(f"مرادف {p}_بدائيا = بدائي_{p};")
    w("")
    aliases = []
    for ar, en, bits, signed in TYPES:
        lo, hi = bounds(bits, signed)
        T = ar
        w(f"// {T} ({en})")
        for op, enop in [("جمع", "add"), ("طرح", "sub"), ("ضرب", "mul")]:
            name = f"{op}_{T}_ملتف"
            w(f"عام عرف {name}(أ: {T}, ب: {T}): {T} {{ أرجع {op}_ملتف_بدائيا(أ, ب); }}")
            aliases.append((f"wrapping_{enop}_{en}", name))
        for side, enop in [("يسرى", "shl"), ("يمنى", "shr")]:
            name = f"إزاحة_{side}_{T}_ملتفة"
            w(f"عام عرف {name}(القيمة: {T}, المقدار: ط32): {T} {{ أرجع إزاحة_{side}_ملتفة_بدائيا(القيمة, المقدار مثل {T}); }}")
            aliases.append((f"wrapping_{enop}_{en}", name))
        # checked
        def emit(name, en_name, body):
            if name in EXISTING:
                return
            w(body)
            aliases.append((en_name, name))
        if signed:
            emit(f"جمع_{T}_متحقق", f"checked_add_{en}",
                 f"عام عرف جمع_{T}_متحقق(أ: {T}, ب: {T}): اختياري {T} {{\n"
                 f"    دع الناتج: {T} = جمع_ملتف_بدائيا(أ, ب);\n"
                 f"    إذا ((ب < 0) != (الناتج < أ)) {{ أرجع اختياري.لا_شيء(); }};\n"
                 f"    أرجع اختياري.موجود(الناتج);\n}}")
            emit(f"طرح_{T}_متحقق", f"checked_sub_{en}",
                 f"عام عرف طرح_{T}_متحقق(أ: {T}, ب: {T}): اختياري {T} {{\n"
                 f"    دع الناتج: {T} = طرح_ملتف_بدائيا(أ, ب);\n"
                 f"    إذا ((ب < 0) != (الناتج > أ)) {{ أرجع اختياري.لا_شيء(); }};\n"
                 f"    أرجع اختياري.موجود(الناتج);\n}}")
            if bits <= 32:
                emit(f"ضرب_{T}_متحقق", f"checked_mul_{en}",
                     f"عام عرف ضرب_{T}_متحقق(أ: {T}, ب: {T}): اختياري {T} {{\n"
                     f"    // The exact product fits 64 bits: no division, no wrapping.\n"
                     + narrow_mul(T, bits, signed, lo, hi, "أرجع اختياري.موجود(@);", "أرجع اختياري.لا_شيء();") + "}")
            else:
              emit(f"ضرب_{T}_متحقق", f"checked_mul_{en}",
                 f"عام عرف ضرب_{T}_متحقق(أ: {T}, ب: {T}): اختياري {T} {{\n"
                 f"    إذا (أ == 0 || ب == 0) {{ أرجع اختياري.موجود(0); }};\n"
                 f"    // -1 * MIN and MIN * -1 overflow; MIN / -1 would trap below.\n"
                 f"    إذا (أ == -1) {{ إذا (ب == {lo}) {{ أرجع اختياري.لا_شيء(); }}; أرجع اختياري.موجود(-ب); }};\n"
                 f"    إذا (ب == -1) {{ إذا (أ == {lo}) {{ أرجع اختياري.لا_شيء(); }}; أرجع اختياري.موجود(-أ); }};\n"
                 f"    دع الناتج: {T} = ضرب_ملتف_بدائيا(أ, ب);\n"
                 f"    إذا (الناتج / أ != ب) {{ أرجع اختياري.لا_شيء(); }};\n"
                 f"    أرجع اختياري.موجود(الناتج);\n}}")
            emit(f"جمع_{T}_مشبع", f"saturating_add_{en}",
                 f"عام عرف جمع_{T}_مشبع(أ: {T}, ب: {T}): {T} {{\n"
                 f"    دع الناتج: {T} = جمع_ملتف_بدائيا(أ, ب);\n"
                 f"    إذا ((ب < 0) != (الناتج < أ)) {{ إذا (ب < 0) {{ أرجع {lo}; }}; أرجع {hi}; }};\n"
                 f"    أرجع الناتج;\n}}")
            emit(f"طرح_{T}_مشبع", f"saturating_sub_{en}",
                 f"عام عرف طرح_{T}_مشبع(أ: {T}, ب: {T}): {T} {{\n"
                 f"    دع الناتج: {T} = طرح_ملتف_بدائيا(أ, ب);\n"
                 f"    إذا ((ب < 0) != (الناتج > أ)) {{ إذا (ب > 0) {{ أرجع {lo}; }}; أرجع {hi}; }};\n"
                 f"    أرجع الناتج;\n}}")
            emit(f"ضرب_{T}_مشبع", f"saturating_mul_{en}",
                 f"عام عرف ضرب_{T}_مشبع(أ: {T}, ب: {T}): {T} {{\n"
                 f"    طابق ضرب_{T}_متحقق_داخليا(أ, ب) مع\n"
                 f"    | اختياري.موجود(الناتج) -> {{ أرجع الناتج; }}\n"
                 f"    | اختياري.لا_شيء -> {{ إذا ((أ < 0) != (ب < 0)) {{ أرجع {lo}; }}; أرجع {hi}; }};\n}}")
            # private copy so saturating mul works even where the checked one lives elsewhere
            if bits <= 32:
                w(f"عرف ضرب_{T}_متحقق_داخليا(أ: {T}, ب: {T}): اختياري {T} {{\n"
                  + narrow_mul(T, bits, signed, lo, hi, "أرجع اختياري.موجود(@);", "أرجع اختياري.لا_شيء();") + "}")
            else:
              w(f"عرف ضرب_{T}_متحقق_داخليا(أ: {T}, ب: {T}): اختياري {T} {{\n"
              f"    إذا (أ == 0 || ب == 0) {{ أرجع اختياري.موجود(0); }};\n"
              f"    إذا (أ == -1) {{ إذا (ب == {lo}) {{ أرجع اختياري.لا_شيء(); }}; أرجع اختياري.موجود(-ب); }};\n"
              f"    إذا (ب == -1) {{ إذا (أ == {lo}) {{ أرجع اختياري.لا_شيء(); }}; أرجع اختياري.موجود(-أ); }};\n"
              f"    دع الناتج: {T} = ضرب_ملتف_بدائيا(أ, ب);\n"
              f"    إذا (الناتج / أ != ب) {{ أرجع اختياري.لا_شيء(); }};\n"
              f"    أرجع اختياري.موجود(الناتج);\n}}")
        else:
            emit(f"جمع_{T}_متحقق", f"checked_add_{en}",
                 f"عام عرف جمع_{T}_متحقق(أ: {T}, ب: {T}): اختياري {T} {{\n"
                 f"    دع الناتج: {T} = جمع_ملتف_بدائيا(أ, ب);\n"
                 f"    إذا (الناتج < أ) {{ أرجع اختياري.لا_شيء(); }};\n"
                 f"    أرجع اختياري.موجود(الناتج);\n}}")
            emit(f"طرح_{T}_متحقق", f"checked_sub_{en}",
                 f"عام عرف طرح_{T}_متحقق(أ: {T}, ب: {T}): اختياري {T} {{\n"
                 f"    إذا (أ < ب) {{ أرجع اختياري.لا_شيء(); }};\n"
                 f"    أرجع اختياري.موجود(أ - ب);\n}}")
            if bits <= 32:
                emit(f"ضرب_{T}_متحقق", f"checked_mul_{en}",
                     f"عام عرف ضرب_{T}_متحقق(أ: {T}, ب: {T}): اختياري {T} {{\n"
                     f"    // The exact product fits 64 bits: no division, no wrapping.\n"
                     + narrow_mul(T, bits, signed, lo, hi, "أرجع اختياري.موجود(@);", "أرجع اختياري.لا_شيء();") + "}")
                emit(f"ضرب_{T}_مشبع", f"saturating_mul_{en}",
                     f"عام عرف ضرب_{T}_مشبع(أ: {T}, ب: {T}): {T} {{\n"
                     + narrow_mul(T, bits, signed, lo, hi, "أرجع @;", f"أرجع {hi};") + "}")
                pass
            else:
              emit(f"ضرب_{T}_متحقق", f"checked_mul_{en}",
                   f"عام عرف ضرب_{T}_متحقق(أ: {T}, ب: {T}): اختياري {T} {{\n"
                   f"    إذا (أ == 0) {{ أرجع اختياري.موجود(0); }};\n"
                   f"    دع الناتج: {T} = ضرب_ملتف_بدائيا(أ, ب);\n"
                   f"    إذا (الناتج / أ != ب) {{ أرجع اختياري.لا_شيء(); }};\n"
                   f"    أرجع اختياري.موجود(الناتج);\n}}")
            emit(f"جمع_{T}_مشبع", f"saturating_add_{en}",
                 f"عام عرف جمع_{T}_مشبع(أ: {T}, ب: {T}): {T} {{\n"
                 f"    دع الناتج: {T} = جمع_ملتف_بدائيا(أ, ب);\n"
                 f"    إذا (الناتج < أ) {{ أرجع {hi}; }};\n"
                 f"    أرجع الناتج;\n}}")
            emit(f"طرح_{T}_مشبع", f"saturating_sub_{en}",
                 f"عام عرف طرح_{T}_مشبع(أ: {T}, ب: {T}): {T} {{\n"
                 f"    إذا (أ < ب) {{ أرجع 0; }};\n"
                 f"    أرجع أ - ب;\n}}")
            if bits > 32:
              emit(f"ضرب_{T}_مشبع", f"saturating_mul_{en}",
                   f"عام عرف ضرب_{T}_مشبع(أ: {T}, ب: {T}): {T} {{\n"
                   f"    إذا (أ == 0) {{ أرجع 0; }};\n"
                   f"    دع الناتج: {T} = ضرب_ملتف_بدائيا(أ, ب);\n"
                   f"    إذا (الناتج / أ != ب) {{ أرجع {hi}; }};\n"
                   f"    أرجع الناتج;\n}}")
        w("")
    for en, ar in aliases:
        w(f"عام مرادف {en} = {ar};")
    OUTPUT.write_text("\n".join(out) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
