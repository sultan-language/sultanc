#!/usr/bin/env python3
"""Generate Stage-0, Stage-1, and qualification token mirrors from the canonical registry."""

from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
REGISTRY = Path(__file__).resolve().parent / "registry/token_registry.def"


@dataclass(frozen=True)
class Token:
    identity: str
    constructor: str
    category: str
    lifecycle: str
    payload: str


@dataclass(frozen=True)
class Keyword:
    identity: str
    english: str
    arabic: str


@dataclass(frozen=True)
class DeprecatedKeyword:
    identity: str
    old: str
    new: str


@dataclass(frozen=True)
class BoolKeyword:
    english: str
    arabic: str
    value: int


@dataclass(frozen=True)
class Operator:
    identity: str
    spelling: str


TOKEN_RE = re.compile(
    r'^SULTANC__TOKEN__\(([A-Z0-9_]+),\s*"([^"]+)",\s*([A-Za-z_]+),\s*([A-Za-z_]+),\s*([A-Za-z_]+)\)$'
)
KEYWORD_RE = re.compile(
    r'^SULTANC__KEYWORD__\(([A-Z0-9_]+),\s*"([^"]+)",\s*"([^"]+)"\)$'
)
DEPRECATED_RE = re.compile(
    r'^SULTANC__KEYWORD_DEPRECATED__\(([A-Z0-9_]+),\s*"([^"]+)",\s*"([^"]+)"\)$'
)
BOOL_RE = re.compile(
    r'^SULTANC__BOOL_KEYWORD__\("([^"]+)",\s*"([^"]+)",\s*([01])\)$'
)
OP_RE = re.compile(r'^SULTANC__OPERATOR__\(([A-Z0-9_]+),\s*"([^"]+)"\)$')


def parse_registry() -> tuple[
    list[Token], list[Keyword], list[BoolKeyword], list[Operator], list[DeprecatedKeyword]
]:
    tokens: list[Token] = []
    keywords: list[Keyword] = []
    deprecated: list[DeprecatedKeyword] = []
    bools: list[BoolKeyword] = []
    operators: list[Operator] = []
    for raw in REGISTRY.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("/*") or line.startswith("*") or line.startswith("*/"):
            continue
        if match := TOKEN_RE.fullmatch(line):
            tokens.append(Token(*match.groups()))
        elif match := KEYWORD_RE.fullmatch(line):
            keywords.append(Keyword(*match.groups()))
        elif match := DEPRECATED_RE.fullmatch(line):
            deprecated.append(DeprecatedKeyword(*match.groups()))
        elif match := BOOL_RE.fullmatch(line):
            english, arabic, value = match.groups()
            bools.append(BoolKeyword(english, arabic, int(value)))
        elif match := OP_RE.fullmatch(line):
            operators.append(Operator(*match.groups()))
        else:
            raise SystemExit(f"unrecognized token registry line: {raw}")
    identities = [token.identity for token in tokens]
    if len(identities) != len(set(identities)):
        raise SystemExit("duplicate token identity in canonical registry")
    known = set(identities)
    for entry in [*keywords, *operators]:
        if entry.identity not in known:
            raise SystemExit(f"surface entry targets unknown token: {entry.identity}")
    aliases = [item for keyword in keywords for item in (keyword.english, keyword.arabic)]
    aliases += [item for keyword in bools for item in (keyword.english, keyword.arabic)]
    aliases += [entry.old for entry in deprecated]
    if len(aliases) != len(set(aliases)):
        raise SystemExit("duplicate keyword spelling in canonical registry")
    keyword_by_id = {keyword.identity: keyword for keyword in keywords}
    for entry in deprecated:
        keyword = keyword_by_id.get(entry.identity)
        if keyword is None:
            raise SystemExit(f"deprecated spelling targets a token without keyword spellings: {entry.identity}")
        if entry.new not in (keyword.english, keyword.arabic):
            raise SystemExit(f"deprecated spelling {entry.old!r} must name its canonical spelling, not {entry.new!r}")
    spellings = [operator.spelling for operator in operators]
    if len(spellings) != len(set(spellings)):
        raise SystemExit("duplicate operator spelling in canonical registry")
    return tokens, keywords, bools, operators, deprecated


def token_source(tokens: list[Token]) -> str:
    constructors = "\n".join(f"    | {token.constructor}" for token in tokens)
    return f'''// GENERATED by tools/generate/generate_token_surface.py from token_registry.def.\n// Do not edit token identities here; edit the canonical registry and regenerate.\n\nعام نوع رمز =\n{constructors}\n;\n'''



def token_identity_source(
    tokens: list[Token], keywords: list[Keyword], operators: list[Operator]
) -> str:
    keyword_by_id = {keyword.identity: keyword for keyword in keywords}
    # A token with two operator spellings (`؟` and `?`) shows the Arabic-script
    # one in Arabic text and the ASCII one in English text.
    operator_by_id = {operator.identity: operator for operator in operators}
    arabic_operator_by_id = {
        operator.identity: operator
        for operator in operators
        if not operator.spelling.isascii()
    }
    fallback_en = {
        "IDENTIFIER": "identifier",
        "LIT_INT": "integer literal",
        "LIT_FLO": "floating-point literal",
        "LIT_STR": "string literal",
        "LIT_CHAR": "character literal",
        "LIT_BOOL": "boolean literal",
        "EOF": "end of file",
        "UNDERSCORE_WITH_INDEX": "indexed placeholder",
    }
    fallback_ar = {
        "IDENTIFIER": "معرف",
        "LIT_INT": "حرفي عدد صحيح",
        "LIT_FLO": "حرفي عدد عشري",
        "LIT_STR": "حرفي نص",
        "LIT_CHAR": "حرفي حرف",
        "LIT_BOOL": "حرفي منطقي",
        "EOF": "نهاية الملف",
        "UNDERSCORE_WITH_INDEX": "موضع مرقم",
    }

    def display(token: Token, language: str) -> str:
        if token.identity in keyword_by_id:
            keyword = keyword_by_id[token.identity]
            return keyword.english if language == "en" else keyword.arabic
        if language == "ar" and token.identity in arabic_operator_by_id:
            return arabic_operator_by_id[token.identity].spelling
        if token.identity in operator_by_id:
            ascii_spellings = [
                operator.spelling
                for operator in operators
                if operator.identity == token.identity and operator.spelling.isascii()
            ]
            if ascii_spellings:
                return ascii_spellings[0]
            return operator_by_id[token.identity].spelling
        mapping = fallback_en if language == "en" else fallback_ar
        if token.identity in mapping:
            return mapping[token.identity]
        return token.identity.lower().replace("_", "-") if language == "en" else token.constructor

    lines = [
        "// GENERATED by tools/generate/generate_token_surface.py from token_registry.def.",
        "// Stable token identity and bilingual display spellings derived from the canonical registry.",
        "",
        'استورد compiler.frontend.lexer.token;',
        'استورد compiler.diagnostics.schema;',
        'استورد compiler.ispeak.ispeak;',
        'استورد compiler.ispeak.keys.surface;',
        "",
        "عام عرف اسم_هوية_رمز(القيمة: رمز): نص {",
        "    طابق القيمة مع",
    ]
    for token in tokens:
        lines += [
            f"    | رمز.{token.constructor} -> {{",
            f"        أرجع «{token.constructor}»;",
            "    }",
        ]
    lines += ["    ;", "}", ""]
    # Tokens without a spelling are described in words; iSpeak owns those words.
    described = {
        "IDENTIFIER": "وصف_معرف",
        "LIT_INT": "وصف_عدد_صحيح",
        "LIT_FLO": "وصف_عدد_عشري",
        "LIT_STR": "وصف_نص",
        "LIT_CHAR": "وصف_حرف",
        "LIT_BOOL": "وصف_منطقي",
        "EOF": "وصف_نهاية_الملف",
        "UNDERSCORE_WITH_INDEX": "وصف_عنصر_نائب_مرقم",
    }
    for fn_name, language in (("تهجئة_عرض_رمز_إنجليزية", "en"), ("تهجئة_عرض_رمز_عربية", "ar")):
        lines += [f"عام عرف {fn_name}(القيمة: رمز): نص {{", "    طابق القيمة مع"]
        lang_ctor = "الإنجليزية" if language == "en" else "العربية"
        for token in tokens:
            if token.identity in described:
                body = f"        أرجع نص_المترجم(لغة_تشخيص.{lang_ctor}(), مفتاح_نص_مترجم.{described[token.identity]}());"
            else:
                body = f"        أرجع «{display(token, language)}»;"
            lines += [
                f"    | رمز.{token.constructor} -> {{",
                body,
                "    }",
            ]
        lines += ["    ;", "}", ""]
    return "\n".join(lines)


def payload_registry_source(tokens: list[Token]) -> str:
    mapping = {
        "None": "بلا",
        "Index": "فهرس",
        "Integer": "عدد_صحيح",
        "Text": "بايتات_نص",
        "Character": "محرف",
        "Boolean": "منطق",
    }
    lines = [
        "// GENERATED by tools/generate/generate_token_surface.py from token_registry.def.",
        "// Canonical token-to-payload contract. Constructors and accessors must obey this mapping.",
        "",
        'استورد compiler.frontend.lexer.token;',
        "",
        "عام نوع فئة_حمولة_رمز =",
        "    | بلا",
        "    | فهرس",
        "    | عدد_صحيح",
        "    | بايتات_نص",
        "    | محرف",
        "    | منطق",
        ";",
        "",
        "عام عرف فئة_حمولة_الرمز(القيمة: رمز): فئة_حمولة_رمز {",
        "    طابق القيمة مع",
    ]
    for token in tokens:
        lines += [
            f"    | رمز.{token.constructor} -> {{",
            f"        أرجع فئة_حمولة_رمز.{mapping[token.payload]}();",
            "    }",
        ]
    lines += ["    ;", "}", ""]
    return "\n".join(lines)

def keyword_registry_source(
    tokens: list[Token], keywords: list[Keyword], bools: list[BoolKeyword],
    deprecated: list[DeprecatedKeyword]
) -> str:
    by_id = {token.identity: token for token in tokens}
    grouped: dict[tuple[int, int], list[tuple[str, str]]] = {}
    for keyword in keywords:
        ctor = by_id[keyword.identity].constructor
        result = f"مطابقة_كلمة.محجوزة(رمز.{ctor}())"
        for spelling in (keyword.english, keyword.arabic):
            encoded = spelling.encode("utf-8")
            grouped.setdefault((encoded[0], len(encoded)), []).append((spelling, result))
    # A deprecated spelling lexes as its token; the warning is a separate query.
    for entry in deprecated:
        ctor = by_id[entry.identity].constructor
        result = f"مطابقة_كلمة.محجوزة(رمز.{ctor}())"
        encoded = entry.old.encode("utf-8")
        grouped.setdefault((encoded[0], len(encoded)), []).append((entry.old, result))
    for keyword in bools:
        value = "صواب" if keyword.value else "خطأ"
        result = f"مطابقة_كلمة.منطقية({value})"
        for spelling in (keyword.english, keyword.arabic):
            encoded = spelling.encode("utf-8")
            grouped.setdefault((encoded[0], len(encoded)), []).append((spelling, result))

    lines = [
        "// GENERATED by tools/generate/generate_token_surface.py from token_registry.def.",
        "// Spelling comes only from the token registry; semantic identity description is frontend-owned.",
        "",
        'استورد compiler.frontend.lexer.token;',
        'استورد compiler.frontend.identifier_identity;',
        'استورد compiler.frontend.lexer.keywords.matching;',
        "",
        "عام عرف كلمة_مسجلة(",
        "    النص: &نص,",
        "    البداية: طبيعي,",
        "    النهاية: طبيعي",
        "): مطابقة_كلمة {",
        "    دع الوصف: وصف_هوية_معرف = صف_هوية_معرف_في_شريحة(النص, البداية, النهاية);",
        "    لو (!الوصف.صالح || !الوصف.لها_محتوى) {",
        "        أرجع مطابقة_كلمة.غير_محجوزة();",
        "    };",
    ]
    first_bytes = sorted({key[0] for key in grouped})
    for first in first_bytes:
        lines += [f"    لو (الوصف.البايت_الأول == {first}) {{"]
        widths = sorted(width for byte, width in grouped if byte == first)
        for width in widths:
            lines += [f"        لو (الوصف.الطول == {width}) {{"]
            for spelling, result in grouped[(first, width)]:
                lines += [
                    f"            لو (تطابق_هوية_معرف_وشريحة(النص, البداية, النهاية, «{spelling}»)) {{",
                    f"                أرجع {result};",
                    "            };",
                ]
            lines += ["        };"]
        lines += ["    };"]
    lines += ["    أرجع مطابقة_كلمة.غير_محجوزة();", "}", ""]
    return "\n".join(lines)


def deprecated_registry_source(tokens: list[Token], deprecated: list[DeprecatedKeyword]) -> str:
    by_id = {token.identity: token for token in tokens}
    lines = [
        "// GENERATED by tools/generate/generate_token_surface.py from token_registry.def.",
        "// Deprecated keyword spellings (SULTANC__KEYWORD_DEPRECATED__). The lexer already",
        "// accepts each one as its token; this query names the spelling a token was",
        "// written in when it is deprecated, for the one warning per use.",
        "",
        'استورد compiler.frontend.lexer.token;',
        'استورد compiler.frontend.identifier_identity;',
        "",
        "عام نوع تهجئة_كلمة_مهجورة = {",
        "    القديمة: نص,",
        "    الجديدة: نص",
        "};",
        "",
        "عام عرف تهجئة_مهجورة_لرمز(",
        "    النوع: رمز,",
        "    النص: &نص,",
        "    البداية: طبيعي,",
        "    النهاية: طبيعي",
        "): اختياري تهجئة_كلمة_مهجورة {",
    ]
    grouped: dict[str, list[DeprecatedKeyword]] = {}
    for entry in deprecated:
        grouped.setdefault(entry.identity, []).append(entry)
    if not grouped:
        lines += ["    أرجع اختياري.لا_شيء();", "}", ""]
        return "\n".join(lines)
    lines += ["    طابق النوع مع"]
    for token in tokens:
        if token.identity not in grouped:
            continue
        lines += [f"    | رمز.{token.constructor} -> {{"]
        for entry in grouped[token.identity]:
            lines += [
                f"        لو (تطابق_هوية_معرف_وشريحة(النص, البداية, النهاية, «{entry.old}»)) {{",
                f"            دع التهجئة: تهجئة_كلمة_مهجورة = {{ القديمة: «{entry.old}», الجديدة: «{entry.new}» }};",
                "            أرجع اختياري.موجود(التهجئة);",
                "        };",
            ]
        lines += ["        أرجع اختياري.لا_شيء();", "    }"]
    lines += ["    | _ -> {", "        أرجع اختياري.لا_شيء();", "    };", "}", ""]
    return "\n".join(lines)


def semantic_registry_source(tokens: list[Token]) -> str:
    keyword_ctors = [token.constructor for token in tokens if token.category == "Keyword"]
    future_ctors = [token.constructor for token in tokens if token.lifecycle == "Future_Reserved"]
    lines = [
        "// GENERATED by tools/generate/generate_token_surface.py from token_registry.def.",
        "// Semantic classification is derived; consumers must not repeat token sets.",
        "",
        'استورد compiler.frontend.lexer.token;',
        "",
        "عام عرف هل_كلمة_محجوزة(القيمة: رمز): منطقي {",
        "    طابق القيمة مع",
    ]
    for ctor in keyword_ctors:
        lines += [f"    | رمز.{ctor} -> {{", "        أرجع صواب;", "    }"]
    lines += ["    | _ -> {", "        أرجع خطأ;", "    };", "}", ""]
    lines += ["عام عرف هل_رمز_مستقبلي(القيمة: رمز): منطقي {", "    طابق القيمة مع"]
    for ctor in future_ctors:
        lines += [f"    | رمز.{ctor} -> {{", "        أرجع صواب;", "    }"]
    lines += ["    | _ -> {", "        أرجع خطأ;", "    };", "}", ""]
    return "\n".join(lines)


def operator_source(tokens: list[Token], operators: list[Operator]) -> str:
    by_id = {token.identity: token for token in tokens}
    # Registry order is canonical maximal-munch order; verify it rather than silently sorting.
    lengths = [len(item.spelling.encode("utf-8")) for item in operators]
    for index in range(1, len(lengths)):
        if lengths[index] > lengths[index - 1]:
            raise SystemExit("operator registry must be ordered longest-first")
    lines = [
        "// GENERATED by tools/generate/generate_token_surface.py from token_registry.def.",
        "",
        'استورد compiler.frontend.lexer.token;',
        'استورد std.text.compare;',
        "",
        "عام نوع مطابقة_عامل =",
        "    | ليس_عاملا",
        "    | عامل بنوع (رمز, عدد)",
        ";",
        "",
        "عام عرف العامل_عند(النص: &نص, الموضع: طبيعي): مطابقة_عامل {",
    ]
    for operator in operators:
        ctor = by_id[operator.identity].constructor
        width = len(operator.spelling.encode("utf-8"))
        lines += [
            f"    لو (يطابق_عند(النص, الموضع, «{operator.spelling}»)) {{",
            f"        أرجع مطابقة_عامل.عامل(رمز.{ctor}(), {width});",
            "    };",
        ]
    lines += ["    أرجع مطابقة_عامل.ليس_عاملا();", "}", ""]
    return "\n".join(lines)


def outputs() -> dict[Path, str]:
    tokens, keywords, bools, operators, deprecated = parse_registry()
    return {
        ROOT / "bootstrap/include/private/frontend/lexer/token_registry.def": REGISTRY.read_text(encoding="utf-8"),
        ROOT / "compiler/frontend/lexer/token.sn": token_source(tokens),
        ROOT / "compiler/frontend/lexer/token_identity.sn": token_identity_source(tokens, keywords, operators),
        ROOT / "compiler/frontend/lexer/payload_registry.sn": payload_registry_source(tokens),
        ROOT / "compiler/frontend/lexer/keywords/keyword_registry.sn": keyword_registry_source(
            tokens, keywords, bools, deprecated
        ),
        ROOT / "compiler/frontend/lexer/keywords/deprecated_registry.sn": deprecated_registry_source(
            tokens, deprecated
        ),
        ROOT / "compiler/frontend/lexer/token_registry.sn": semantic_registry_source(tokens),
        ROOT / "compiler/frontend/lexer/operators.sn": operator_source(tokens, operators),
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    mismatches: list[str] = []
    for path, content in outputs().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                mismatches.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if mismatches:
        print("token surface generation: FAIL", file=sys.stderr)
        for mismatch in mismatches:
            print(f"- generated file is stale: {mismatch}", file=sys.stderr)
        return 1
    if args.check:
        print("token surface generation: PASS")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
