#!/usr/bin/env python3
"""Generate std's FreeBSD system-call number table.

The table maps the std kernel operations (tools/generate/registry/
freebsd_syscalls.def) to FreeBSD SYS_ numbers, read from sys/sys/syscall.h
through `clang -E -dM` for every supported architecture. FreeBSD numbers its
system calls once (sys/kern/syscalls.master), so the generator checks that
every architecture agrees and writes one table; each row also carries the
call's prototype from syscalls.master, so the arguments std passes can be
checked against it.

Headers: a FreeBSD source tree (or the subset of it these headers include):

  git clone --depth 1 -b releng/14.2 https://github.com/freebsd/freebsd-src
  tools/generate/generate_freebsd_syscalls.py --src freebsd-src
"""
import argparse, os, re, subprocess, tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT_FILE = ROOT / "library/std/os/platform/unix/freebsd/syscalls/numbers.sn"
REGISTRY = ROOT / "tools/generate/registry/freebsd_syscalls.def"

# clang architecture -> FreeBSD machine directory (sys/<dir>/include).
ARCHES = {"x86_64": "amd64", "aarch64": "arm64", "riscv64": "riscv"}
RELEASE = "freebsd14.2"


def include_root(src, machine):
    """The installed /usr/include layout, as links into the source tree."""
    root = tempfile.mkdtemp(prefix="freebsd-include-")
    links = {"sys": "sys/sys", "machine": f"sys/{machine}/include", "x86": "sys/x86/include",
             "netinet": "sys/netinet", "netinet6": "sys/netinet6"}
    for name, rel in links.items():
        if (Path(src) / rel).is_dir():
            os.symlink(Path(src).resolve() / rel, Path(root) / name)
    return root


def clang_args(src, arch):
    root = include_root(src, ARCHES[arch])
    return ["clang", f"--target={arch}-unknown-{RELEASE}", "-nostdinc",
            "-isystem", root, "-isystem", str(Path(src).resolve() / "include")]


def macros(src, arch, headers):
    cmd = clang_args(src, arch) + ["-E", "-dM"]
    for h in headers:
        cmd += ["-include", h]
    text = subprocess.run(cmd + ["-"], input="", capture_output=True, text=True, check=True).stdout
    table = {}
    for line in text.splitlines():
        m = re.match(r"#define (\w+) (.+)", line)
        if m:
            table[m.group(1)] = m.group(2).strip()
    return table


def prototypes(src):
    """name -> prototype text of the current (non-COMPAT) syscalls.master entry."""
    text = (Path(src) / "sys/kern/syscalls.master").read_text(encoding="utf-8")
    text = re.sub(r"\\\n", " ", text)
    found = {}
    for m in re.finditer(r"^(\d+)\s+\w+\s+([A-Z|]+)\s*\{(.*?)\}", text, re.M | re.S):
        if "COMPAT" in m.group(2) or "OBSOL" in m.group(2) or "UNIMPL" in m.group(2):
            continue
        # Drop the source annotations (_In_z_, _Out_writes_bytes_(n), ...).
        proto = re.sub(r"(?<!\w)_[A-Z]\w*(\([^)]*\))?\s*", "", m.group(3))
        proto = re.sub(r"\s+", " ", proto).strip()
        proto = proto.replace("( ", "(").replace(" )", ")").rstrip(";")
        name = re.search(r"(\w+)\s*\(", proto)
        if name:
            found.setdefault(name.group(1), proto)
    return found


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", required=True, help="FreeBSD source tree (sys/, include/)")
    args = ap.parse_args()
    rows = []
    for line in REGISTRY.read_text(encoding="utf-8").splitlines():
        if line.strip() and not line.startswith("#"):
            parts = line.split()
            rows.append((parts[0], parts[1:]))
    tables = {arch: macros(args.src, arch, ["sys/syscall.h"]) for arch in ARCHES}
    protos = prototypes(args.src)
    lines = [
        "// GENERATED by tools/generate/generate_freebsd_syscalls.py. Do not edit.",
        "استورد os.platform.unix.linux.syscalls.operations;",
        "",
        "// FreeBSD sys/sys/syscall.h (from sys/kern/syscalls.master): one numbering",
        "// for amd64, arm64 and riscv, checked on each. The registry",
        "// (tools/generate/registry/freebsd_syscalls.def) says which FreeBSD call",
        "// provides each std kernel operation; its prototype follows each row.",
        "// These are numbers only: the LLVM provider's kernel entry issues them.",
        "عام عرف رقم_نداء_نواة_فري_بي_إس_دي(العملية: عملية_نداء_نواة_لينكس): طبيعي {",
        "    طابق العملية مع",
    ]
    for i, (op, names) in enumerate(rows):
        value, note = None, None
        for nr in names:
            if nr == "-":
                value, note = 0xFFFFFFFF, "none: never issued on FreeBSD"
                break
            values = {arch: table.get("SYS_" + nr) for arch, table in tables.items()}
            if None in values.values():
                continue
            if len(set(values.values())) != 1:
                raise SystemExit(f"SYS_{nr} differs between architectures: {values}")
            value = int(next(iter(values.values())))
            note = f"SYS_{nr}: " + protos.get(nr, nr + "(?)")
            break
        if value is None:
            raise SystemExit(f"no SYS_ number for {op} ({names})")
        end = ";" if i + 1 == len(rows) else ""
        lines.append(f"    | عملية_نداء_نواة_لينكس.{op} -> {{ أرجع {value}; }}{end} // {note}")
    lines += ["}", ""]
    OUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUT_FILE.write_text("\n".join(lines), encoding="utf-8")
    print("->", OUT_FILE.relative_to(ROOT))


if __name__ == "__main__":
    main()
