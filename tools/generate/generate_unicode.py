#!/usr/bin/env python3
"""Generate SultanC Unicode 18.0.0 data from the Unicode Consortium UCD.

The generator consumes *only* the pinned UCD and never Python's unicodedata,
ICU, or the host OS Unicode database. Numeric vectors are initialized once at
module scope. Their lowering is a separate compiler implementation concern.

Usage:
    python3 tools/generate/generate_unicode.py --ucd /path/to/18.0.0/ucd

Normative source: https://www.unicode.org/Public/18.0.0/ucd/
UAX #15: https://www.unicode.org/reports/tr15/
UAX #29: https://www.unicode.org/reports/tr29/
UAX #44: https://www.unicode.org/reports/tr44/
"""
from __future__ import annotations

import argparse
from collections import defaultdict
from hashlib import sha256
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "library/std/unicode/data"
VERSION = "18.0.0"

CATEGORY_CODES = ("Lu", "Ll", "Lt", "Lm", "Lo", "Mn", "Mc", "Me", "Nd", "Nl", "No", "Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po", "Sm", "Sc", "Sk", "So", "Zs", "Zl", "Zp", "Cc", "Cf", "Cs", "Co", "Cn")
PROPERTIES = ("Alphabetic", "Numeric", "Uppercase", "Lowercase", "White_Space", "Cased", "Case_Ignorable", "Grapheme_Extend", "Default_Ignorable_Code_Point", "XID_Start", "XID_Continue")
BREAK_FILES = ("GraphemeBreakProperty", "WordBreakProperty", "SentenceBreakProperty")
BREAK_NAMES = {
    "GraphemeBreakProperty": ("Other", "CR", "LF", "Control", "L", "V", "T", "LV", "LVT", "Extend", "ZWJ", "SpacingMark", "Prepend", "Regional_Indicator"),
    "WordBreakProperty": ("Other", "CR", "LF", "Newline", "Extend", "Format", "ZWJ", "WSegSpace", "ALetter", "Hebrew_Letter", "Numeric", "Katakana", "ExtendNumLet", "MidLetter", "MidNum", "MidNumLet", "Single_Quote", "Double_Quote", "Regional_Indicator"),
    "SentenceBreakProperty": ("Other", "CR", "LF", "Sep", "Extend", "Format", "Sp", "Lower", "Upper", "OLetter", "Numeric", "ATerm", "STerm", "Close", "SContinue"),
}


def require(ucd: Path, filename: str) -> tuple[str, bytes]:
    path = ucd / filename
    if not path.is_file():
        raise FileNotFoundError(f"Unicode {VERSION} input missing: {path}")
    raw = path.read_bytes()
    if not raw or b"\0" in raw:
        raise ValueError(f"invalid empty/binary UCD input: {filename}")
    text = raw.decode("utf-8-sig")
    header = re.search(r"^#\s*\S+?-(\d+\.\d+\.\d+)\.txt", text[:1000], re.M)
    if header and header.group(1) != VERSION:
        raise ValueError(f"{filename}: mixed UCD version {header.group(1)}")
    return text, raw


def intervals(text: str, name: str) -> list[tuple[int, int]]:
    result = []
    for lineno, line in enumerate(text.splitlines(), 1):
        body = line.partition("#")[0].strip()
        if not body:
            continue
        fields = [x.strip() for x in body.split(";")]
        if len(fields) < 2:
            raise ValueError(f"{name}:{lineno}: missing property")
        cp = fields[0].split("..")
        if len(cp) not in (1, 2):
            raise ValueError(f"{name}:{lineno}: malformed range")
        try:
            start, end = int(cp[0], 16), int(cp[-1], 16)
        except ValueError as exc:
            raise ValueError(f"{name}:{lineno}: nonhex code point") from exc
        if start > end or end > 0x10FFFF:
            raise ValueError(f"{name}:{lineno}: invalid range")
        result.append((start, end, fields[1] + "=" + fields[2] if len(fields) > 2 and fields[1] == "InCB" else fields[1]))
    return result


def coalesce(items):
    merged = []
    for start, end, prop in sorted(items, key=lambda x: (x[2], x[0], x[1])):
        if merged and merged[-1][2] == prop and start <= merged[-1][1] + 1:
            if start <= merged[-1][1]:
                raise ValueError(f"overlapping UCD ranges for {prop}: {start:06X}")
            merged[-1] = (merged[-1][0], end, prop)
        else:
            merged.append((start, end, prop))
    return merged


def file_header(inputs):
    return ("// Generated by tools/generate/generate_unicode.py; DO NOT EDIT.\n"
            f"// UCD {VERSION}; source: https://www.unicode.org/Public/{VERSION}/ucd/\n"
            "// Version and SHA-256 provenance is recorded by the generator.\n")


def numeric_vector(name: str, numbers, width=32):
    # Top-level vectors are static *source declarations*, not runtime strings.
    rows = []
    values = [str(x) for x in numbers]
    for i in range(0, len(values), 16):
        rows.append("    " + ", ".join(values[i:i + 16]) + ("," if i + 16 < len(values) else ""))
    return (f"عام دع {name}: متجه غ{width} = [\n" + "\n".join(rows) + "\n];\n")


def emit(name, *chunks):
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text(file_header(None) + "\n".join(chunks), encoding="utf-8")


def parse_unicode_data(text):
    data = {}
    opened = None
    for lineno, line in enumerate(text.splitlines(), 1):
        fields = line.split(";")
        if len(fields) != 15:
            raise ValueError(f"UnicodeData.txt:{lineno}: expected 15 columns")
        cp = int(fields[0], 16)
        if cp > 0x10FFFF or cp in data:
            raise ValueError(f"UnicodeData.txt:{lineno}: invalid or repeated scalar")
        if fields[1].endswith(", First>"):
            if opened is not None:
                raise ValueError("nested UnicodeData range")
            opened = (cp, fields)
            continue
        if fields[1].endswith(", Last>"):
            if opened is None or cp <= opened[0]:
                raise ValueError("unmatched UnicodeData range")
            for v in range(opened[0], cp + 1):
                data[v] = opened[1]
            opened = None
            continue
        if opened is not None:
            raise ValueError("unterminated UnicodeData range")
        data[cp] = fields
    if opened is not None:
        raise ValueError("unterminated UnicodeData range")
    return data


def dense_ranges(entries, default):
    output = []
    previous = 0
    for cp, value in sorted(entries.items()):
        if value == default:
            continue
        if output and output[-1][1] + 1 == cp and output[-1][2] == value:
            output[-1] = (output[-1][0], cp, value)
        else:
            output.append((cp, cp, value))
        previous = cp
    return output


def parse_mappings(text, kind):
    result = {}
    for lineno, raw in enumerate(text.splitlines(), 1):
        part = raw.partition("#")[0].strip()
        if not part:
            continue
        fields = [x.strip() for x in part.split(";")]
        if kind == "fold":
            if len(fields) != 3 or fields[1] not in ("C", "F", "S", "T"):
                raise ValueError(f"CaseFolding.txt:{lineno}: invalid entry")
            if fields[1] == "T":
                continue  # Turkic locale fold is NOT the default fold.
            cp = int(fields[0], 16)
            result.setdefault(cp, {})[fields[1]] = tuple(int(x, 16) for x in fields[2].split())
        else:
            if len(fields) != 5:
                raise ValueError(f"SpecialCasing.txt:{lineno}: invalid entry")
            cp = int(fields[0], 16)
            # Locale-sensitive mappings are intentionally not added to default tables.
            # Final_Sigma is handled by Unicode's text casing algorithm.
            if fields[4] and fields[4] != "Final_Sigma":
                continue
            result.setdefault(cp, {})["conditional" if fields[4] else "default"] = (
                tuple(int(x, 16) for x in fields[1].split()),
                tuple(int(x, 16) for x in fields[2].split()),
                tuple(int(x, 16) for x in fields[3].split()),
            )
    return result


def mapping_tables(name, mapping):
    """Key-indexed variable-length scalar sequences; identity omitted."""
    keys, offsets, lengths, scalars = [], [], [], []
    for key, seq in sorted(mapping.items()):
        seq = tuple(seq)
        if seq == (key,):
            continue
        if not seq:
            raise ValueError(f"empty mapping for U+{key:04X}")
        keys.append(key)
        offsets.append(len(scalars))
        lengths.append(len(seq))
        scalars.extend(seq)
    return [numeric_vector(f"{name}_مفاتيح", keys),
            numeric_vector(f"{name}_بدايات", offsets),
            numeric_vector(f"{name}_أطوال", lengths),
            numeric_vector(f"{name}_قيم", scalars)]


def main(ucd: Path):
    manifest = []
    names = [
        "ReadMe.txt", "UnicodeData.txt", "DerivedCoreProperties.txt", "PropList.txt",
        "SpecialCasing.txt", "CaseFolding.txt", "DerivedNormalizationProps.txt",
        "CompositionExclusions.txt", "auxiliary/GraphemeBreakProperty.txt",
        "auxiliary/WordBreakProperty.txt", "auxiliary/SentenceBreakProperty.txt",
        "emoji/emoji-data.txt",
    ]
    inputs = {}
    for name in names:
        body, raw = require(ucd, name)
        inputs[name] = body
        manifest.append((name, sha256(raw).hexdigest()))
    if VERSION not in inputs["ReadMe.txt"]:
        raise ValueError("ReadMe.txt: Unicode 18.0.0 version not confirmed")
    ud = parse_unicode_data(inputs["UnicodeData.txt"])
    # General category and CCC, using the exact 30 categories in existing API.
    cats = dense_ranges({cp: CATEGORY_CODES.index(f[2]) for cp, f in ud.items()}, 29)
    emit("categories.sn", numeric_vector("نطاقات_فئات_يونيكود", [n for a,b,c in cats for n in (a,b,c)]))
    ccc = dense_ranges({cp: int(f[3]) for cp,f in ud.items() if int(f[3])}, 0)
    # Derived numeric property also covers nondecimal numeric values in UnicodeData.
    props = defaultdict(list)
    for key in ("DerivedCoreProperties.txt", "PropList.txt"):
        for start,end,prop in intervals(inputs[key],key):
            if prop in PROPERTIES:
                props[prop].append((start,end,prop))
    for cp, f in ud.items():
        if f[8]:
            props["Numeric"].append((cp,cp,"Numeric"))
    # Ensures Numeric is the union of Numeric_Type=Decimal/Digit/Numeric.
    encoded = []
    for idx,prop in enumerate(PROPERTIES):
        merged = []
        for a,b,_ in sorted(props[prop]):
            if merged and a <= merged[-1][1] + 1:
                merged[-1] = (merged[-1][0],max(b, merged[-1][1]))
            else:
                merged.append((a,b))
        encoded.extend((idx,a,b) for a,b in merged)
    emit("properties.sn", numeric_vector("نطاقات_خواص_يونيكود", [n for row in encoded for n in row]))
    sp = parse_mappings(inputs["SpecialCasing.txt"], "special")
    fold = parse_mappings(inputs["CaseFolding.txt"], "fold")
    upper, lower, simple_upper, simple_lower, full_fold, simple_fold = {}, {}, {}, {}, {}, {}
    for cp,fields in ud.items():
        if fields[12]: simple_upper[cp] = (int(fields[12],16),)
        if fields[13]: simple_lower[cp] = (int(fields[13],16),)
        if cp in simple_upper: upper[cp] = simple_upper[cp]
        if cp in simple_lower: lower[cp] = simple_lower[cp]
    for cp,mapping in sp.items():
        if "default" in mapping:
            low, title, up = mapping["default"]
            lower[cp] = low; upper[cp] = up
    for cp,mapping in fold.items():
        simple = mapping.get("S", mapping.get("C"))
        full = mapping.get("F", mapping.get("C", simple))
        if simple is not None: simple_fold[cp] = simple
        if full is not None: full_fold[cp] = full
    emit("case_mapping.sn", *(mapping_tables("تحويل_أحرف_كبيرة", upper)
                                + mapping_tables("تحويل_أحرف_صغيرة", lower)
                                + mapping_tables("تحويل_كبير_بسيط", simple_upper)
                                + mapping_tables("تحويل_صغير_بسيط", simple_lower)))
    emit("case_folding.sn", *(mapping_tables("طي_حالة_كامل", full_fold)
                                + mapping_tables("طي_حالة_بسيط", simple_fold)))
    # Recursive decompositions are resolved by the runtime algorithm, including Hangul.
    decomp_canon, decomp_compat = {}, {}
    for cp,f in ud.items():
        raw = f[5]
        if not raw: continue
        bits = raw.split()
        compatible = bits[0].startswith("<")
        if compatible: bits = bits[1:]
        seq = tuple(int(x,16) for x in bits)
        if compatible: decomp_compat[cp] = seq
        else: decomp_canon[cp] = seq
    # UAX #15 full composition exclusion is versioned in DerivedNormalizationProps.txt.
    excluded = set()
    for a,b,p in intervals(inputs["DerivedNormalizationProps.txt"], "DerivedNormalizationProps.txt"):
        if p == "Full_Composition_Exclusion":
            excluded.update(range(a,b+1))
    pairs = {}
    for cp, seq in decomp_canon.items():
        if len(seq) == 2 and cp not in excluded and int(ud[seq[0]][3]) == 0:
            pair = (seq[0],seq[1])
            if pair in pairs: raise ValueError(f"duplicate canonical pair {pair}")
            pairs[pair] = cp
    emit("normalization.sn", numeric_vector("نطاقات_درجة_دمج_يونيكود", [n for a,b,c in ccc for n in (a,b,c)]),
         *mapping_tables("تفكيك_قانوني", decomp_canon),
         *mapping_tables("تفكيك_توافقي", decomp_compat),
         numeric_vector("أزواج_تركيب_يونيكود", [n for (a,b),c in sorted(pairs.items()) for n in (a,b,c)]))
    # Segmentation: default Other class represented as zero. Property name
    # enumerations are kept in the generator and runtime in identical order.
    segments = []
    for filename in BREAK_FILES:
        names = BREAK_NAMES[filename]
        data = intervals(inputs[f"auxiliary/{filename}.txt"], filename)
        segment = []
        for a,b,p in data:
            if p not in names: raise ValueError(f"{filename}: unsupported class {p}")
            if p != "Other": segment.append((a,b,names.index(p)))
        segment.sort()
        segments.append(numeric_vector(f"نطاقات_{filename}",[n for row in segment for n in row]))
    # Extended_Pictographic is part of the versioned emoji data.
    ext = [(a,b,1) for a,b,p in intervals(inputs["emoji/emoji-data.txt"],"emoji-data.txt") if p == "Extended_Pictographic"]
    segments.append(numeric_vector("نطاقات_تصويرية_موسعة",[n for row in sorted(ext) for n in row]))
    incb = [(a,b,{"Consonant":1,"Extend":2,"Linker":3}[p.split("=",1)[1].strip()])
            for a,b,p in intervals(inputs["DerivedCoreProperties.txt"],"DerivedCoreProperties.txt")
            if p.startswith("InCB") and "=" in p]
    incb.sort()
    segments.append(numeric_vector("نطاقات_وصل_هندي",[n for row in incb for n in row]))
    emit("segmentation.sn", *segments)
    emit("version.sn", 'عام عرف إصدار_بيانات_يونيكود_داخلية(): نص { أرجع «18.0.0»; }\n')
    OUT.joinpath("SOURCE_SHA256.txt").write_text(
        f"Unicode {VERSION}\nSource https://www.unicode.org/Public/{VERSION}/ucd/\n"
        + "".join(f"{digest}  {name}\n" for name,digest in manifest), encoding="utf-8")
    print(f"Generated {len(list(OUT.glob('*.sn')))} Unicode {VERSION} data modules from {len(manifest)} verified inputs")


if __name__ == "__main__":
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument("--ucd", type=Path, required=True, help="Unicode 18.0.0 UCD root")
    args = cli.parse_args()
    main(args.ucd)
