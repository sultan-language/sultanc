#!/usr/bin/env python3
"""Generate compiler/interpreter/execution/host_kernel_generated.sn.

The interpreter forwards a validated raw Linux syscall to the host kernel.
Each of the six machine slots is either a scalar word or a staged byte
buffer, and SultanC has no integer/pointer casts, so every slot layout
(6 bits -> 64 layouts) is spelled out as its own typed raw call.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "compiler/interpreter/execution/host_kernel_generated.sn"
GUARD = '(الهدف.المنصة == «linux» && (الهدف.المعمارية == «x86_64» || الهدف.المعمارية == «aarch64»))'
PARAMS = ("    القناع: طبيعي, الرقم: ط64,\n"
          "    و1: ط64, و2: ط64, و3: ط64, و4: ط64, و5: ط64, و6: ط64,\n"
          "    ب1: &متغير متجه ط8, ب2: &متغير متجه ط8, ب3: &متغير متجه ط8,\n"
          "    ب4: &متغير متجه ط8, ب5: &متغير متجه ط8, ب6: &متغير متجه ط8\n")


def slot(mask: int, i: int) -> str:
    return f"&متغير (*ب{i})[0]" if mask & (1 << (i - 1)) else f"و{i}"


def main() -> None:
    lines = [
        "// GENERATED by tools/generate/generate_host_kernel.py. Do not edit.",
        "// Host side of the interpreter's raw Linux syscall. The interpreter has",
        "// already authenticated the operation, classified every slot and staged",
        "// each buffer; bit i-1 of the mask marks slot i as a buffer. Every buffer",
        "// passed here holds at least one byte. The raw kernel call is the one",
        "// operation here the compiler cannot prove safe, so it sits in an",
        "// explicit unsafe scope after the interpreter's checks.",
        f"إذا {GUARD} {{",
        "    عام عرف نفذ_نداء_نواة_مضيف(",
        PARAMS.replace("\n    ", "\n        ").replace("    القناع", "        القناع", 1).rstrip("\n"),
        "    ): ط64 {",
        "        دع الناتج: متغير ط64 = 0;",
    ]
    for mask in range(64):
        args = ", ".join(slot(mask, i) for i in range(1, 7))
        lines.append(f"        إذا (القناع == {mask}) {{ غير_آمن {{ الناتج := بدائي_نداء_نواة_خام(الرقم, {args}); }} أرجع الناتج; }};")
    lines += [
        "        أرجع 0 مثل ط64;",
        "    }",
        "}",
        "",
        f"إذا (!{GUARD}) {{",
        "    عام عرف نفذ_نداء_نواة_مضيف(",
        PARAMS.replace("\n    ", "\n        ").replace("    القناع", "        القناع", 1).rstrip("\n"),
        "    ): ط64 {",
        "        أرجع 0 مثل ط64;",
        "    }",
        "}",
        "",
        "// The interpreted target must use the host's syscall numbering.",
        "// 1 = x86_64, 2 = aarch64, 0 = no host kernel bridge.",
        'إذا (الهدف.المنصة == «linux» && الهدف.المعمارية == «x86_64») {',
        "    عام عرف معمارية_نواة_المضيف(): طبيعي { أرجع 1; }",
        "}",
        'إذا (الهدف.المنصة == «linux» && الهدف.المعمارية == «aarch64») {',
        "    عام عرف معمارية_نواة_المضيف(): طبيعي { أرجع 2; }",
        "}",
        f"إذا (!{GUARD}) {{",
        "    عام عرف معمارية_نواة_المضيف(): طبيعي { أرجع 0; }",
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
